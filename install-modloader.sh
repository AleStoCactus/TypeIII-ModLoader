#!/usr/bin/env bash
# Type III Mod Loader 1.0.0 - Linux installer
#
# Put this file in the Type III game folder and run it:
#   ./install-modloader.sh               install or update
#   ./install-modloader.sh --uninstall   remove the mod loader (your mods/ folder is kept)
#   add -y to answer "yes" to every question
#
# Everything needed is embedded at the end of this file.
set -euo pipefail

VERSION="1.0.0"
SELF="$(readlink -f "$0")"
GAME_DIR="$(dirname "$SELF")"
UNINSTALL=0
YES=0

for arg in "$@"; do
	case "$arg" in
		--uninstall|uninstall) UNINSTALL=1 ;;
		-y|--yes) YES=1 ;;
		-h|--help) sed -n '2,8p' "$SELF" | sed 's/^# \{0,1\}//'; exit 0 ;;
		*) echo "Unknown option: $arg (use --help)"; exit 2 ;;
	esac
done

ask() {
	[ "$YES" = 1 ] && return 0
	if [ ! -t 0 ]; then
		echo "$1 [y/N] -> no (not interactive, use -y)"
		return 1
	fi
	local answer
	read -r -p "$1 [y/N] " answer
	case "$answer" in [yYsS]*) return 0 ;; *) return 1 ;; esac
}

find_game() {
	local f name lower
	for f in "$GAME_DIR"/*; do
		[ -f "$f" ] || continue
		name="$(basename "$f")"
		lower="${name,,}"
		case "$lower" in *modloader*) continue ;; esac
		if [[ "$lower" == *.pck ]]; then echo "$name"; return 0; fi
		if [[ "$lower" == typeiii* || "$lower" == "type iii"* ]] && [ -x "$f" ]; then
			echo "$name"; return 0
		fi
	done
	return 1
}

echo "=== Type III Mod Loader $VERSION ==="
echo "Game folder: $GAME_DIR"
echo

if ! GAME_EXE="$(find_game)"; then
	echo "WARNING: no Type III executable found in this folder."
	echo "This file must be placed in the game folder (next to the game executable)."
	ask "Continue anyway?" || { echo "Cancelled."; exit 1; }
else
	echo "Game found: $GAME_EXE"
fi
if [ ! -w "$GAME_DIR" ]; then
	echo "ERROR: the game folder is not writable."
	exit 1
fi

cd "$GAME_DIR"

if [ "$UNINSTALL" = 1 ]; then
	ask "Remove the mod loader? (the mods/ folder is kept)" || { echo "Cancelled."; exit 1; }
	if [ -f override.cfg ] && grep -q 'ModLoader=' override.cfg; then
		if [ -f override.cfg.bak ]; then
			mv -f override.cfg.bak override.cfg
			echo "  ~ override.cfg (your original file was restored)"
		else
			rm -f override.cfg
			echo "  - override.cfg"
		fi
	fi
	for p in modloader MODDING_README.md modding/extract_scripts.py; do
		if [ -e "$p" ]; then rm -rf -- "$p"; echo "  - $p"; fi
	done
	rmdir modding 2>/dev/null || true
	echo
	echo "Mod loader removed. The game is vanilla again (mods/ was kept)."
	exit 0
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
awk 'found { print } /^__PAYLOAD_BELOW__$/ { found = 1 }' "$SELF" | base64 -d | tar -xzf - -C "$TMP"

echo "Installing:"
# Mod loader files: always updated.
while IFS= read -r -d '' f; do
	rel="${f#"$TMP"/}"
	case "$rel" in mods/*|override.cfg) continue ;; esac
	mkdir -p "$(dirname "$rel")"
	cp -f "$f" "$rel"
	echo "  + $rel"
done < <(find "$TMP" -type f -print0 | sort -z)

# Example mods: installed only if not already there.
mkdir -p mods
for d in "$TMP"/mods/*/; do
	name="$(basename "$d")"
	if [ -e "mods/$name" ]; then
		echo "  = mods/$name (already there, kept)"
	else
		cp -r "$d" "mods/$name"
		echo "  + mods/$name"
	fi
done

# override.cfg: hooks the mod loader into the game.
if [ -f override.cfg ] && ! grep -q 'ModLoader=' override.cfg; then
	bak="override.cfg.bak"
	[ -e "$bak" ] && bak="override.cfg.bak.$(date +%Y%m%d%H%M%S)"
	cp override.cfg "$bak"
	printf '\n' >> override.cfg
	cat "$TMP/override.cfg" >> override.cfg
	echo "  + override.cfg (added to your existing file, backup: $bak)"
else
	cp -f "$TMP/override.cfg" override.cfg
	echo "  + override.cfg"
fi

echo
echo "Done! Start the game: your mods are in Settings > Mod."
echo "Put new mods in: $GAME_DIR/mods"
echo "Guide: MODDING_README.md - Uninstall: ./$(basename "$SELF") --uninstall"
exit 0
